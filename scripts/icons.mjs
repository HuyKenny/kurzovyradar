// Builds src/lib/icons.ts from lucide-static (ISC): one consistent outline set for every control icon.
// Re-run after changing NAMES:  node scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const NAMES = ['search', 'star', 'trending-up', 'trending-down', 'arrow-right', 'arrow-up-right', 'arrow-up', 'arrow-down', 'chevron-down', 'chevron-right',
  'x', 'menu', 'clock', 'info', 'radar', 'chart-line', 'calculator', 'book-open', 'external-link', 'sliders-horizontal', 'trophy', 'shield-check',
  'circle-alert', 'equal', 'minus', 'calendar', 'list', 'scale', 'percent', 'activity'];
const out = {};
for (const n of NAMES) {
  const svg = readFileSync(new URL(`../node_modules/lucide-static/icons/${n}.svg`, import.meta.url), 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s*\n\s*/g, '').trim();
}
writeFileSync(new URL('../src/lib/icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs from lucide-static ${JSON.parse(readFileSync(new URL('../node_modules/lucide-static/package.json', import.meta.url))).version} (ISC License).\n` +
  `export const ICONS = ${JSON.stringify(out, null, 1)} as const;\nexport type IconName = keyof typeof ICONS;\n`);
console.log(Object.keys(out).length, 'icons');
